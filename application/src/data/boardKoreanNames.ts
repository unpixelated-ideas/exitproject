const compass: Record<string, string> = { E: '동', W: '서', N: '북', S: '남' };

export function koreanBoardStation(english: string): string | undefined {
  if (Object.hasOwn(names, english)) return names[english];
  const numbered = /^(?:([EWNS]) )?(\d+) (St|Av)$/.exec(english);
  if (!numbered) return undefined;
  const [, direction, number] = numbered;
  return `${direction ? compass[direction] + ' ' : ''}${number}번가`;
}
